ROOT = Path(__file__).resolve().parent
ORDER = ('chapters01_02', *(f'chapter{n:02}' for n in range(3, 11)))
COUNTS = dict(zip(ORDER, (48, 29, 52, 48, 62, 47, 42, 70, 57)))
ENV = dict(os.environ, PYTHONDONTWRITEBYTECODE='1', PYTHONHASHSEED='0',
           PYTHONPATH='', PYTHONNOUSERSITE='1', PYTHONOPTIMIZE='')


def encoded(value):
    return json.dumps(value, indent=2, sort_keys=True, allow_nan=False) + '\n'


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def load(path):
    return json.loads(path.read_text(encoding='utf-8'))


def source_checks():
    """Hash and parse files without importing or executing lesson code."""
    manifest = load(ROOT / 'provenance/LAB_FILES.json')
    actual = {p.relative_to(ROOT).as_posix() for folder in ORDER
              for p in (ROOT / folder).rglob('*') if p.is_file()
              and '__pycache__' not in p.parts and p.suffix != '.pyc'}
    require(actual == set(manifest), 'Active lesson inventory differs from LAB_FILES.json')
    for name, expected in manifest.items():
        path = ROOT / name
        require(not path.is_symlink() and path.resolve().is_relative_to(ROOT), 'Unsafe lesson path')
        require(sha256(path.read_bytes()).hexdigest() == expected, f'Lesson hash differs: {name}')
    readiness = load(ROOT/'provenance/PREREQUISITE_FILES.json')
    readiness_actual = {p.relative_to(ROOT).as_posix() for p in (ROOT/'prerequisites').rglob('*')
                        if p.is_file() and '__pycache__' not in p.parts and p.suffix != '.pyc'}
    require(readiness_actual == set(readiness), 'Readiness lab inventory differs')
    for name, expected in readiness.items():
        path = ROOT/name
        require(not path.is_symlink() and path.resolve().is_relative_to(ROOT/'prerequisites'), 'Unsafe readiness path')
        require(sha256(path.read_bytes()).hexdigest() == expected, f'Readiness file hash differs: {name}')
    archive = ROOT / 'provenance/companion-code-baseline.zip'
    require(sha256(archive.read_bytes()).hexdigest() ==
            '69bfd27af4ed665ce78e09ac9eea07b75092a1d27ed7f09b7156bf0806384e25',
            'Public code baseline identity differs')
    with zipfile.ZipFile(archive) as bundle:
        require(bundle.testzip() is None, 'Public code baseline CRC failure')
        differences = load(ROOT / 'provenance/UPSTREAM_DIFF.json')
        observed = {}
        for name in sorted(actual):
            if name not in bundle.namelist():
                observed[name] = 'added'
            elif (ROOT / name).read_bytes() != bundle.read(name):
                observed[name] = 'changed'
        for name in bundle.namelist():
            if name.split('/')[0] in ORDER and name not in actual:
                observed[name] = 'removed_from_active_tree_preserved_in_archive'
        require(observed == differences, 'Upstream difference classification differs')
        for folder in ORDER:
            for name in ('printed_examples.py','printed_snippets.json'):
                target = f'{folder}/{name}'
                if target in actual:
                    require((ROOT/target).read_bytes() == bundle.read(target),
                            f'Canonical book listing source changed: {target}')
    python_files = [p for p in ROOT.rglob('*.py') if not set(p.relative_to(ROOT).parts) &
                    {'.venv', '.git', 'generated', 'evidence', '__pycache__', 'upstream'}]
    for path in python_files:
        ast.parse(path.read_text(encoding='utf-8'), filename=str(path))
    chapters = load(ROOT / 'docs/chapter-map.json')
    require([r['chapter'] for r in chapters] == list(range(1, 11)), 'Chapter order differs')
    for chapter in chapters:
        require(chapter['suite'] in ORDER, 'Unknown suite')
        require(chapter['prerequisite_lab'] == 'prerequisites/README.md', 'Chapter readiness map differs')
        for name in chapter['paths']:
            require((ROOT / name).is_file(), f'Missing chapter target: {name}')
        for entry in chapter['symbols']:
            tree = ast.parse((ROOT / entry['path']).read_text())
            names = {n.name for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.ClassDef))}
            require(entry['name'] in names, f'Missing concept symbol: {entry}')
    # Local Markdown targets are checked independently of GitHub availability.
    links = 0
    for path in ROOT.rglob('*.md'):
        if set(path.relative_to(ROOT).parts) & {'.venv', '.git', 'generated', 'upstream'} or path.name == 'UPSTREAM_README.md':
            continue
        for target in re.findall(r'\]\(([^)]+)\)', path.read_text()):
            if target.startswith(('http:', 'https:', 'mailto:', '#')):
                continue
            target = target.split('#')[0]
            if target:
                require((path.parent / target).exists(), f'Broken local link: {path.relative_to(ROOT)} -> {target}')
                links += 1
    views = check_views(ROOT)
    refresher_views = check_readiness_views(ROOT)
    prerequisite_map = load(ROOT/'docs/prerequisite-map.json')
    for name in prerequisite_map['paths']:
        require((ROOT/name).is_file(), f'Missing readiness map target: {name}')
    return {'lesson_files_sha256_checked': len(manifest), 'python_files_parsed': len(python_files),
            'readiness_files_sha256_checked':len(readiness),'book_refresher_views_checked':refresher_views,
            'canonical_listing_views_checked': views,
            'chapter_targets_checked': len(chapters), 'local_links_checked': links,
            'original_archive_sha256_checked': True, 'lab_code_executed': False}


def environment_check():
    require(sys.flags.optimize == 0, 'Use Python without -O/-OO; assertions must execute')
    require(platform.python_implementation() == 'CPython' and sys.version_info >= (3, 12),
            'Use CPython 3.12 or newer; see tested versions in docs/SETUP.md')
    # ROW_NUMBER is used by the independent SQL implementation.
    with closing(sqlite3.connect(':memory:')) as db, db:
        require(db.execute('SELECT row_number() OVER (ORDER BY x) FROM (SELECT 1 x)').fetchone() == (1,),
                'SQLite must support window functions (3.25 or newer)')
    with tempfile.TemporaryDirectory(prefix='feature-env-') as folder:
        path = Path(folder) / 'check'; path.write_text('ok')
        require(path.read_text() == 'ok', 'Temporary directory not writable')
    return {'implementation': platform.python_implementation(), 'python': platform.python_version(),
            'sqlite': sqlite3.sqlite_version, 'system': platform.system(), 'machine': platform.machine(),
            'compiler': platform.python_compiler(), 'third_party_packages_required': [],
            'assertions_enabled': True, 'sqlite_window_functions': True}


def compare_json(actual, expected, label, runtime_fields=()):
    """Exclude only explicitly declared runtime leaf values, validating their truth."""
    left, right = deepcopy(actual), deepcopy(expected)
    runtime_values = {'python': platform.python_version(), 'python_version': platform.python_version(),
                      'sqlite': sqlite3.sqlite_version, 'runtime': f'CPython {platform.python_version()}'}
    for field in runtime_fields:
        if field == 'runtime.python_version':
            require(left['runtime']['python_version'] == platform.python_version(), 'False manifest runtime')
            left['runtime'].pop('python_version'); right['runtime'].pop('python_version')
        else:
            require(left[field] == runtime_values[field], f'False runtime metadata: {label}:{field}')
            left.pop(field); right.pop(field)
    require(encoded(left) == encoded(right), f'Expected semantic output differs: {label}')


def reviewed_code_manifest(expected, folder):
    """Apply only versioned, before/after code identities to historical metadata.

    Semantic snapshots are not replaced. Each declaration must match the
    immutable original archive and the separately checked active-file manifest.
    """
    revised = deepcopy(expected)
    changes = load(ROOT/'provenance/RUNTIME_MANIFEST_UPDATES.json')['runtime_manifest_code_updates']
    active = load(ROOT/'provenance/LAB_FILES.json')
    for change in changes:
        if change['folder'] != folder:
            continue
        name = change['source_file']
        require(revised['code_sha256'].get(name) == change['before_sha256'],
                f'Historical code identity differs from reviewed baseline: {folder}/{name}')
        require(active.get(folder+'/'+name) == change['after_sha256'],
                f'Current code identity differs from reviewed correction: {folder}/{name}')
        revised['code_sha256'][name] = change['after_sha256']
    return revised


def reviewed_chapter04_manifest(expected):
    """Check the explicit global-identity correction against historical bytes.

    Only the corrected identity declaration and its current source hash differ;
    dataset values, labels, splits and every other contract remain compared.
    """
    updates = load(ROOT/'provenance/RUNTIME_MANIFEST_UPDATES.json')
    change = updates['chapter04_global_event_identity']
    require(expected['source_sha256'] == change['before_source_sha256'] and
            expected['event_identity'] == ['customer', 'event', 'version'],
            'Historical chapter04 identity differs from reviewed baseline')
    active = load(ROOT/'provenance/LAB_FILES.json')
    ownership = updates['chapter04_sqlite_ownership']
    require(ownership['before_source_sha256'] == change['after_source_sha256'],
            'Reviewed chapter04 ownership predecessor differs from accepted identity correction')
    require(active['chapter04/chapter4.py'] == ownership['after_source_sha256'],
            'Current chapter04 source identity differs from reviewed correction')
    revised = deepcopy(expected)
    revised['source_sha256'] = ownership['after_source_sha256']
    revised['event_identity'] = ['event', 'version']
    return revised

def run_once(folder, destination):
    logs, comparisons, commands = [], [], []
    def run(*args):
        command = [sys.executable, '-B', *args]
        result = subprocess.run(command, cwd=folder, env=ENV, capture_output=True, text=True, timeout=300)
        record = {'argv': ['python', '-B', *args], 'returncode': result.returncode,
                  'stdout': result.stdout, 'stderr': result.stderr}
        commands.append(record)
        (destination / 'commands.json').write_text(encoded(commands))
        require(result.returncode == 0, f'{folder.name}: {args} failed\n{result.stdout}\n{result.stderr}')
        return result.stdout
    def snapshot(command, expected, fields=()):
        output = run(*command)
        compare_json(json.loads(output), load(folder / expected), expected, fields)
        comparisons.append({'expected': expected, 'runtime_fields_compared_separately': list(fields),
                            'observed_stdout_sha256': sha256(output.encode()).hexdigest(), 'status': 'PASS'})
    def artifact(name, expected, fields=()):
        compare_json(load(folder / name), load(folder / expected), name, fields)
        comparisons.append({'expected': expected, 'observed': name, 'status': 'PASS',
                            'runtime_fields_compared_separately': list(fields)})
    # Unittest logs include elapsed times but are excluded from repeat equality.
    run('-m', 'unittest', 'discover', '-s', '.', '-p', 'test_*.py', '-v')
    log = commands[-1]['stderr']
    match = re.search(r'Ran (\d+) tests?', log)
    require(match and int(match.group(1)) == COUNTS[folder.name] and 'skipped=' not in log,
            'Test population changed or was skipped; review it explicitly')
    n = folder.name
    if n == 'chapters01_02':
        snapshot(['foundations_lab.py'], 'expected_outputs/examples.json')
    elif n == 'chapter03':
        snapshot(['historical_lab.py'], 'expected_outputs/examples.json')
        snapshot(['exercise_answers.py'], 'expected_outputs/exercise_answers.json')
        snapshot(['generated_checks.py'], 'expected_outputs/generated_checks.json')
        for args, output in [(['sqlite_lab.py'], '50\n'), (['sqlite_lab.py','--known-at','610'], '85\n'),
                             (['sqlite_lab.py','--window-start','550','--window-end','610','--known-at','610'], '95\n'),
                             (['sqlite_lab.py','--unknown-history'], 'null\n'), (['run_sql_file.py'], '50\n')]:
            require(run(*args) == output, f'SQL expected output differs: {args}')
    elif n in ('chapter04', 'chapter05'):
        main = 'chapter4.py' if n == 'chapter04' else 'chapter5.py'
        snapshot([main], 'expected_output.json')
        if n == 'chapter04':
            compare_json(load(folder/'dataset_rows.json'), load(folder/'expected_output.json')['rows'], 'chapter04 dataset rows')
            original = json.loads(zipfile.ZipFile(ROOT/'provenance/companion-code-baseline.zip').read('chapter04/dataset_manifest.json'))
            original = reviewed_chapter04_manifest(original)
            compare_json(load(folder/'dataset_manifest.json'), original, 'chapter04 manifest', ('python','sqlite'))
            require(run('sample3_original_check.py') == 'Original Chapter 3 function passed five direct assertions.\n', 'Legacy regression mismatch')
        else:
            artifact('comparison.json', 'expected_output.json')
            original = json.loads(zipfile.ZipFile(ROOT/'provenance/companion-code-baseline.zip').read('chapter05/policy_manifest.json'))
            compare_json(load(folder/'policy_manifest.json'), original, 'chapter05 manifest', ('python',))
            expected = 'PASS: seeds 0..499; 500 fixtures; 1000 policy cases; 1396 emitted snapshots checked'
            require(expected in run('randomized_checks.py'), 'Chapter 5 generated population differs')
    elif n == 'chapter06':
        snapshot(['parity_lab.py'], 'expected_outputs/parity_report.json')
        original = json.loads(zipfile.ZipFile(ROOT/'provenance/companion-code-baseline.zip').read('chapter06/generated/manifest.json'))
        original = reviewed_code_manifest(original, 'chapter06')
        compare_json(load(folder/'generated/manifest.json'), original, 'chapter06 manifest', ('python_version',))
        fixture = run('-c', 'from dataclasses import asdict; from parity_lab import build_fixture,canonical_json; t,_=build_fixture(); print(canonical_json(dict(contracts=asdict(t.contracts),key=asdict(t.key),publications=[asdict(r) for r in t.publications],source_revisions=[asdict(r) for r in t.source.revisions])),end="")')
        compare_json(json.loads(fixture),load(folder/'expected_outputs/fixture.json'),'chapter06 fixture')
    elif n == 'chapter07':
        snapshot(['examples.py'], 'expected_outputs/examples.json')
    elif n == 'chapter08':
        snapshot(['examples.py'], 'expected_outputs/examples.json')
        snapshot(['run_mutants.py','--json'], 'expected_outputs/mutation_report.json')
        snapshot(['exercise_answers.py'], 'expected_outputs/exercise_answers.json')
    elif n == 'chapter09':
        run('operations_lab.py', '--output-dir', 'generated')
        for name in ('base_report.json','evidence_packet.json'):
            artifact('generated/'+name, 'expected_outputs/'+name)
        snapshot(['exercise_answers.py'], 'expected_outputs/exercise_answers.json')
    elif n == 'chapter10':
        for case in ('base', 'challenge'):
            run('capstone_lab.py','--case',case,'--output-dir','generated/'+case)
            for expected in sorted((folder/'expected_outputs'/case).glob('*.json')):
                fields = ('runtime.python_version',) if expected.name == 'manifest.json' else ()
                artifact('generated/'+case+'/'+expected.name, str(expected.relative_to(folder)), fields)
            require(run('-c', f'from capstone_lab import verify_artifacts; print(verify_artifacts("generated/{case}")["status"])') == 'PASS\n', 'Capstone readback failed')
        snapshot(['exercise_answers.py'], 'expected_outputs/exercise_answers.json')
    if n in ('chapter04','chapter05'):
        count = 5 if n == 'chapter04' else 6
        words = 'five' if count == 5 else 'six'
        require(run('printed_examples.py') == f'All {words} printed Python listings passed.\n', 'Printed listings differ')
    else:
        snapshot(['printed_examples.py'], 'expected_outputs/printed_examples.json')
        if (folder/'randomized_checks.py').exists():
            snapshot(['randomized_checks.py'], 'expected_outputs/randomized_checks.json', ('runtime',) if n == 'chapter07' else ())
    if (folder/'generated').exists():
        shutil.copytree(folder/'generated', destination/'artifacts')
    for name in ('dataset_rows.json','dataset_manifest.json','comparison.json','policy_manifest.json'):
        if (folder/name).exists(): shutil.copyfile(folder/name,destination/name)
    return {'suite': n, 'status': 'PASS', 'unit_tests': int(match.group(1)),
            'commands_executed': len(commands), 'snapshot_comparisons': comparisons,
            'stdout_sha256_by_command': [sha256(c['stdout'].encode()).hexdigest() for c in commands]}


def run_prerequisites(output):
    """A separate beginner readiness module; it is never counted as a chapter suite."""
    summaries = []
    for number in (1,2):
        destination = output/'prerequisites'/f'run_{number}'
        if destination.exists():shutil.rmtree(destination)
        destination.mkdir(parents=True)
        commands = []
        with tempfile.TemporaryDirectory(prefix='feature-readiness-') as temp:
            clean = Path(temp)/'prerequisites'
            shutil.copytree(ROOT/'prerequisites',clean,ignore=shutil.ignore_patterns('__pycache__','*.pyc'))
            for args in [('-m','unittest','discover','-s','.','-p','test_*.py','-v'),('readiness_lab.py',)]:
                result = subprocess.run([sys.executable,'-B',*args],cwd=clean,env=ENV,capture_output=True,text=True,timeout=60)
                commands.append({'argv':['python','-B',*args],'stdout':result.stdout,'stderr':result.stderr,'returncode':result.returncode})
                (destination/'commands.json').write_text(encoded(commands))
                require(result.returncode == 0, 'Readiness command failed: '+result.stdout+result.stderr)
            match = re.search(r'Ran (\d+) tests?',commands[0]['stderr'])
            require(match and int(match[1]) == 12 and 'skipped=' not in commands[0]['stderr'], 'Readiness test population differs')
            actual = json.loads(commands[1]['stdout'])
            compare_json(actual,load(clean/'expected_output.json'),'prerequisite lab')
            (destination/'observed.json').write_text(encoded(actual))
            summaries.append({'status':'PASS','unit_tests':12,'book_refresher_examples':2,
                              'expected_output_sha256':sha256(encoded(actual).encode()).hexdigest()})
    require(summaries[0] == summaries[1], 'Readiness clean runs differ')
    return {**summaries[0],'clean_runs':2,'two_clean_results_equal':True}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--chapter', choices=[f'{n:02}' for n in range(1, 11)])
    parser.add_argument('--source-only', '--integrity-only', action='store_true', dest='source_only')
    parser.add_argument('--check-env', action='store_true')
    parser.add_argument('--prerequisites-only', action='store_true', help='run the beginner readiness lab, zero chapter suites')
    args = parser.parse_args()
    if args.prerequisites_only and (args.chapter or args.source_only or args.check_env):
        parser.error('--prerequisites-only must be used by itself')
    output = ROOT/'generated'; output.mkdir(exist_ok=True)
    label = 'source' if args.source_only else 'environment' if args.check_env else 'prerequisites' if args.prerequisites_only else args.chapter or 'all'
    target = output/f'verification_{label}.json'
    target.write_text(encoded({'status':'RUNNING'}))
    started = time.monotonic()
    started_utc = datetime.now(timezone.utc).isoformat()
    try:
        integrity = source_checks()
        runtime = None if args.source_only else environment_check()
        results = []
        readiness = None
        if not args.source_only and not args.check_env:
            if args.prerequisites_only or not args.chapter:
                print('Verifying beginner readiness lab twice in clean copies ...',file=sys.stderr,flush=True)
                readiness = run_prerequisites(output)
            selected = [] if args.prerequisites_only else [('chapters01_02' if args.chapter in ('01','02') else 'chapter'+args.chapter)] if args.chapter else ORDER
            for name in selected:
                print(f'Verifying {name} twice in clean copies ...', file=sys.stderr, flush=True)
                runs = []
                for number in (1, 2):
                    destination = output/name/f'run_{number}'
                    if destination.exists(): shutil.rmtree(destination)
                    destination.mkdir(parents=True)
                    with tempfile.TemporaryDirectory(prefix='feature-book-') as temp:
                        clean = Path(temp)/name; shutil.copytree(ROOT/name,clean,ignore=shutil.ignore_patterns('__pycache__','*.pyc'))
                        runs.append(run_once(clean,destination))
                require(runs[0] == runs[1], f'Two clean summaries differ: {name}')
                results.append({**runs[0], 'clean_runs':2,'two_clean_results_equal':True})
        result = {'status':'PASS','runtime':runtime,'source_checks':integrity,
                  'prerequisite_lab_executed':readiness is not None,'prerequisite_lab':readiness,
                  'lab_suites_executed':len(results),'suites':results,'external_mutations':False,
                  'started_utc':started_utc,
                  'completed_utc':datetime.now(timezone.utc).isoformat(),
                  'duration_seconds':round(time.monotonic()-started,3),
                  'counting_rule':'Each per-suite unit-test count is reported once; overlaps and repeated runs are not unique tests.'}
        target.write_text(encoded(result)); print(encoded(result),end=''); return 0
    except Exception as error:
        result = {'status':'FAIL','error':str(error)}
        target.write_text(encoded(result)); print(encoded(result),file=sys.stderr,end=''); return 1


if __name__ == '__main__':
    raise SystemExit(main())
